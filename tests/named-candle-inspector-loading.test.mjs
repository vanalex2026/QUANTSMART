import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../mfe_ux_lab/cockpit/package.json", import.meta.url));
const ts = require("typescript"), React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const source = readFileSync(new URL("../mfe_ux_lab/cockpit/src/components/ChartPatternInspector.tsx", import.meta.url), "utf8");
const ast = ts.createSourceFile("Inspector.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
let section;
function visit(node) {
  if (ts.isJsxElement(node) && node.openingElement.tagName.getText(ast) === "section" && (node.getText(ast).includes("<h3>Historical evidence</h3>") || node.getText(ast).includes("<h3>{copy.history}</h3>"))) section = node.getText(ast);
  ts.forEachChild(node, visit);
}
visit(ast);
assert.ok(section, "test executes the actual historical evidence section");
const code = ts.transpileModule(`function renderHistory(signal, namedHistoryStatus, namedHistory, onRetryNamedHistory, knowledge=null, evidenceStatus, onRetryEvidence) {
 const evidence=null,occurrences=namedHistory?.history || [],copy={history:'Historical evidence'};
 const NamedCandleHistoryEvidence=()=>React.createElement('strong',null,'completed census');
 return (${section});
}`, { compilerOptions: { jsx: ts.JsxEmit.React, target: ts.ScriptTarget.ES2022 } }).outputText;
const renderHistory = new Function("React", `${code};return renderHistory;`)(React);
const signal = { annotationKind: "named_candle" };
const pending = renderToStaticMarkup(renderHistory(signal, "loading", null));
assert.match(pending, /Scanning retained M5 candle history/);
assert.match(pending, /Historical occurrence count is pending/);
assert.doesNotMatch(pending, /0 retained matching analogue|completed census/);
let retries = 0;
const errorTree = renderHistory(signal, "error", null, () => retries++);
const collect = node => !node || typeof node !== "object" ? [] : [node, ...React.Children.toArray(node.props?.children).flatMap(collect)];
const retry = collect(errorTree).find(node => node.type === "button");
assert.equal(retry.props.children, "Retry named-candle history scan");
retry.props.onClick();
assert.equal(retries, 1, "rendered retry invokes the worker retry callback");
assert.match(renderToStaticMarkup(errorTree), /Historical occurrence count is unavailable/);
const ready = renderToStaticMarkup(renderHistory(signal, "ready", { history: [{ time: "t" }] }));
assert.match(ready, /completed census/);
assert.match(ready, /1 measured historical occurrences/);
assert.doesNotMatch(ready, /Scanning retained|count is pending|retained analogue preview/);
const pdfSignal = { annotationKind: "price_action" };
const pdfPending = renderToStaticMarkup(renderHistory(pdfSignal, "error", null, undefined, { id: "pattern_break" }, "loading"));
assert.match(pdfPending, /Scanning retained M5 history/);
assert.match(pdfPending, /Historical occurrence count is pending/);
let pdfRetries = 0;
const pdfErrorTree = renderHistory(pdfSignal, "loading", null, undefined, { id: "pattern_break" }, "error", () => pdfRetries++);
const pdfError = renderToStaticMarkup(pdfErrorTree);
assert.match(pdfError, /Pattern history statistics are unavailable/);
assert.match(pdfError, /Historical occurrence count is unavailable/);
assert.doesNotMatch(pdfError, /count is pending/, "failed PDF history must not imply an active scan, regardless of named-history state");
collect(pdfErrorTree).find(node => node.type === "button").props.onClick();
assert.equal(pdfRetries, 1, "PDF history retry invokes its own callback");
const microscope = readFileSync(new URL("../mfe_ux_lab/cockpit/src/pages/Microscope.tsx", import.meta.url), "utf8");
assert.match(microscope, /useNamedCandleHistory\(detectorBars, inspectedNamedPattern, focused && tf === "M5"\)/);
assert.doesNotMatch(microscope, /scanNamedCandleHistory\(/, "the render never runs a synchronous full named-history scan");
console.log("NAMED CANDLE INSPECTOR LOADING PASS: actual pending/error/ready markup and retry preserve asynchronous full-history semantics.");
