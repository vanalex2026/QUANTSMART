import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(new URL("../mfe_ux_lab/cockpit/package.json", import.meta.url));
const { build } = require("esbuild");
const bundled = await build({ stdin: { contents: 'export * from "./src/lib/historicalPatternPosition.ts"; export * from "./src/components/HistoricalPositionOverlay.tsx";', resolveDir: fileURLToPath(new URL("../mfe_ux_lab/cockpit/", import.meta.url)), loader: "tsx" }, jsx: "automatic", bundle: true, format: "cjs", platform: "node", external: ["react", "react/jsx-runtime"], write: false, logLevel: "silent" });
const mod = { exports: {} };
new Function("require", "module", "exports", bundled.outputFiles[0].text)(require, mod, mod.exports);
const { historicalPatternPosition: position, historicalPositionInViewport: visible, currentLandmarksInViewport: current, HistoricalPositionOverlay } = mod.exports;
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const bar = (i, extra = {}) => ({ t: new Date(Date.UTC(2026, 0, 1, 0, i * 5)).toISOString(), o: 100, h: 101, l: 99, c: 100, closed: true, ...extra });
const bars = Array.from({ length: 40 }, (_, i) => bar(i));
const signal = { time: bars[10].t, reads: "bullish", label: "HIST SUPPORT RESISTANCE", i: 99999 };
const long = position(bars, signal);
assert.equal(long.index, 10, "UTC identity overrides a stale signal ordinal");
assert.equal(long.endIndex, 34, "an unresolved path stops at the 24-bar horizon");
assert.equal(long.state, "TIMEOUT");
assert.equal(long.entry, 100); assert.equal(long.target, 104.4); assert.equal(long.invalidation, 98);
assert.equal(long.side, "LONG");
const short = position(bars, { ...signal, reads: "bearish" });
assert.equal(short.side, "SHORT");
assert.equal(short.target, 95.6); assert.equal(short.invalidation, 102);
const shifted = position(bars.slice(3), signal);
assert.equal(shifted.index, 7);
for (const key of ["entry", "target", "invalidation", "localAtr"]) assert.equal(shifted[key], long[key], "retention shifts preserve setup geometry while its prefix remains retained");
const hitTape = bars.map((b, i) => i === 12 ? { ...b, h: 105 } : b);
const hit = position(hitTape, signal);
assert.equal(hit.state, "TARGET_FIRST"); assert.equal(hit.endIndex, 12);
for (const key of ["entry", "target", "invalidation", "localAtr"]) assert.equal(hit[key], long[key], "observed future outcomes cannot reprice a selected setup");
const ambiguous = position(bars.map((b, i) => i === 11 ? { ...b, h: 105, l: 97 } : b), signal);
assert.equal(ambiguous.state, "AMBIGUOUS"); assert.equal(ambiguous.endIndex, 11);
const gapped = position(bars.filter((_, i) => i !== 12), signal);
assert.equal(gapped.state, "DATA_GAP"); assert.equal(gapped.endIndex, 11, "the shaded observed path must not cross the missing transition");
const forming = position(bars.map((b, i) => i === 11 ? { ...b, closed: false } : b), signal);
assert.equal(forming.endIndex, 10, "forming context cannot extend the historical study");
assert.equal(position(bars.map((b, i) => i === 9 ? { ...b, h: NaN } : b), signal), null);
const offGridTape = bars.map((b) => ({ ...b, t: new Date(Date.parse(b.t) + 60_000).toISOString() }));
assert.equal(position(offGridTape, { ...signal, time: offGridTape[10].t }), null, "contiguous but off-grid observations cannot acquire a historical M5 position overlay");
for (const time of ["invalid", bar(-1).t, bars.at(-1).t]) assert.equal(position(bars, { ...signal, time }), null, "missing/current selections cannot bypass current-source gates");
assert.equal(position(bars, { ...signal, reads: "neutral" }), null);
assert.equal(position([], signal), null); assert.equal(position(bars, null), null);
assert.equal(visible(long, 0, 9, null), null); assert.equal(visible(long, 35, 39, null), null);
assert.equal(visible(long, 11, 13, null), long, "panning past the anchor still displays the observed portion");
assert.equal(visible(long, 0, 39, 9), null, "a replay cursor cannot reveal a future setup");
assert.equal(visible(long, 0, 39, 10), null, "a known setup cannot reveal outcome geometry before its observed path exists");
assert.equal(visible(hit, 0, 39, 11), null, "a future target event remains hidden before its closed candle");
assert.equal(visible(hit, 0, 39, 12), hit, "the observed target event becomes visible at its closed candle");
assert.equal(current(true, 20, 39, false), false, "current landmarks must not appear in a historical viewport");
assert.equal(current(true, 39, 39, true), false, "explicit historical geometry takes precedence when the tail is also visible");
assert.equal(current(true, 39, 39, false), true, "Reset to the retained tail restores current-source landmarks");
assert.equal(current(true, 39, 39, false, 38), false, "a tail viewport must not reveal current-source levels beyond the replay cursor");
assert.equal(current(true, 39, 39, false, 0), false, "a replay cursor at zero also withholds current-source landmarks");
assert.equal(current(true, 39, 39, false, 39), true, "revealing the retained tail restores current-source landmarks");
assert.equal(current(true, 39, 39, false, null), true, "a cleared replay cursor preserves current-source visibility");
assert.equal(current(false, 20, 39, true), true, "legacy replay overlays retain their existing semantics");
assert.equal(current(false, 39, 39, false, 0), true, "cursor gating applies only to latest-source landmarks");

const markup = (p, extra = {}) => renderToStaticMarkup(createElement("svg", null, createElement(HistoricalPositionOverlay, { position: p, xFor: i => i * 10, yFor: price => 500 - price * 3, left: 0, right: 400, top: 0, bottom: 250, ...extra })));
for (const p of [long, short, ambiguous]) {
  const svg = markup(p);
  assert.match(svg, new RegExp(`data-historical-position="${p.side}"`));
  assert.match(svg, new RegExp(`data-position-state="${p.state}"`));
  assert.match(svg, /SHADOW_ONLY; NO_DECISION; no order authority/);
  assert.equal((svg.match(/data-position-level=/g) || []).length, 3);
  assert.doesNotMatch(svg, /NaN|Infinity/);
}
const areas = markup(long, { layer: "areas" });
assert.match(areas, /aria-hidden="true"/); assert.equal((areas.match(/fill-opacity="0.16"/g) || []).length, 2);
assert.doesNotMatch(areas, /data-historical-position/, "background and foreground layers must expose one position announcement");
assert.doesNotMatch(markup(long), /fill-opacity="0.16"/, "foreground captions must not tint candles");
assert.doesNotMatch(markup(long, { left: 380 }), /data-historical-position/, "a completely clipped position produces no stray labels");
console.log("HISTORICAL PATTERN POSITION PASS: UTC identity, causal prices, bounded observed path, current/historical ownership and actual SVG rendering.");
