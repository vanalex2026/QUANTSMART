import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(new URL("../mfe_ux_lab/cockpit/package.json", import.meta.url));
const { build } = require("esbuild");
const bundled = await build({ entryPoints: [fileURLToPath(new URL("../mfe_ux_lab/cockpit/src/lib/patternBarrierOutcomes.ts", import.meta.url))], bundle: true, format: "esm", platform: "node", write: false, logLevel: "silent" });
const { patternBarrierOutcome: study, measurePatternBarrierOutcomes: measure } = await import("data:text/javascript;base64," + Buffer.from(bundled.outputFiles[0].text).toString("base64"));
const bar = (i, fields = {}) => ({ t: new Date(Date.UTC(2026, 0, 1, 0, i * 5)).toISOString(), o: 100, h: 101, l: 99, c: 100, closed: true, ...fields });
const setup = Array.from({ length: 7 }, (_, i) => bar(i));
const tape = (...future) => [...setup, ...future.map((fields, i) => bar(i + 7, fields))];
const target = study(tape({ h: 105, c: 104 }), 6, "UP");
assert.equal(target.state, "TARGET_FIRST");
assert.equal(target.entry, 100);
assert.equal(target.target, 104.4);
assert.equal(target.invalidation, 98);
assert.equal(target.observedBars, 1);
assert.equal(target.resolvedAt, bar(7).t);
assert.equal(study(tape({ l: 97, c: 98 }), 6, "UP").state, "INVALIDATION_FIRST");
assert.equal(study(tape({ l: 95, c: 96 }), 6, "DOWN").state, "TARGET_FIRST");
assert.equal(study(tape({ h: 103, c: 102 }), 6, "DOWN").state, "INVALIDATION_FIRST");
assert.equal(study(tape({ h: 105, l: 97 }), 6, "UP").state, "AMBIGUOUS", "OHLC cannot establish which barrier was touched first");
assert.equal(study(tape({ h: 103, l: 95 }), 6, "DOWN").state, "AMBIGUOUS");
assert.equal(study(tape({ o: 105, h: 106, l: 97 }), 6, "UP").state, "TARGET_FIRST", "a known opening print beyond target precedes a later invalidation touch");
assert.equal(study(tape({ o: 97, h: 105, l: 96 }), 6, "UP").state, "INVALIDATION_FIRST");
assert.equal(study(tape({ o: 95, h: 103, l: 94 }), 6, "DOWN").state, "TARGET_FIRST");
assert.equal(study(tape({ o: 103, h: 104, l: 95 }), 6, "DOWN").state, "INVALIDATION_FIRST");
assert.equal(study(tape({ h: 104.4 }), 6, "UP").state, "TARGET_FIRST", "exact boundary touches count");
assert.equal(study(tape({ l: 98 }), 6, "UP").state, "INVALIDATION_FIRST");
assert.equal(study(tape(...Array(24).fill({})), 6, "UP").state, "TIMEOUT");
assert.equal(study(tape(...Array(23).fill({})), 6, "UP").state, "INCOMPLETE");
assert.equal(study(setup, 6, "UP").state, "INCOMPLETE");
assert.equal(study(tape({ h: 110, closed: false }), 6, "UP").state, "INCOMPLETE", "a forming candle cannot resolve a modeled path");
assert.equal(study(tape({ t: bar(8).t, h: 110 }), 6, "UP").state, "DATA_GAP", "a target beyond an unobserved M5 transition does not establish a win");
assert.equal(study(tape({ h: NaN }), 6, "UP").state, "INVALID_DATA");
assert.equal(study(tape({ o: 100, h: 100, l: 100, c: 100 }), 6, "UP").state, "INVALID_DATA", "zero-range OHLC rows stay outside resolved path statistics");
const shiftedGrid = tape({ h: 105 }).map((row) => ({ ...row, t: new Date(Date.parse(row.t) + 60_000).toISOString() }));
assert.equal(study(shiftedGrid, 6, "UP").state, "INVALID_SETUP", "a uniformly off-grid tape is not verified M5 evidence");
assert.equal(study(tape({ t: new Date(Date.parse(bar(7).t) + 60_000).toISOString(), h: 105 }), 6, "UP").state, "INVALID_DATA", "an off-grid future candle cannot resolve a target touch");
assert.equal(study(setup.map((b, i) => i === 3 ? { ...b, t: bar(2).t } : b), 6, "UP").state, "INVALID_SETUP");
assert.equal(study(setup.map((b, i) => i === 3 ? { ...b, closed: false } : b), 6, "UP").state, "INVALID_SETUP");
assert.equal(study(tape({ h: 110, l: 90 }), 6, "NEUTRAL").state, "NEUTRAL");
for (const index of [-1, 0, 99, NaN, 1.5]) assert.equal(study(setup, index, "UP").state, "INVALID_SETUP");
for (const horizon of [0, -1, NaN, 1.5, 289]) assert.equal(study(setup, 6, "UP", horizon).state, "INVALID_SETUP");
const afterResolution = study(tape({ h: 105 }, { h: NaN }), 6, "UP");
assert.equal(afterResolution.state, "TARGET_FIRST", "later invalid data cannot undo an earlier observed first touch");
const futureMutation = study(tape({ h: 110, l: 90, c: 97 }), 6, "UP");
for (const key of ["entry", "target", "invalidation", "localAtr"]) assert.equal(futureMutation[key], target[key], "future data never reprices the fixed setup barriers");
const row = (direction, time = setup[6].t) => ({ i: 6, time, direction, nextBar: "UP", score: 0.5 });
const summary = measure(tape({ h: 105, c: 104 }), [row("UP"), row("DOWN"), row("NEUTRAL"), row("UP", bar(5).t)]);
assert.equal(summary.total, 4);
assert.equal(summary.resolved, 2);
assert.equal(summary.targetFirstRate, 0.5);
assert.equal(summary.counts.TARGET_FIRST, 1);
assert.equal(summary.counts.INVALIDATION_FIRST, 1);
assert.equal(summary.counts.NEUTRAL, 1);
assert.equal(summary.counts.INVALID_SETUP, 1, "retention-shifted ordinals must match the original UTC identity");
assert.equal(Object.values(summary.counts).reduce((sum, count) => sum + count, 0), summary.total);
assert.equal(summary.excluded + summary.resolved, summary.total);
assert.deepEqual(summary.sides, { long: { target: 1, invalidation: 0 }, short: { target: 0, invalidation: 1 } });
const ambiguous = measure(tape({ h: 110, l: 90 }), [row("UP")]);
assert.equal(ambiguous.targetFirstRate, null);
assert.equal(ambiguous.counts.AMBIGUOUS, 1);
assert.equal(ambiguous.excluded, 1);
const offGridSummary = measure(shiftedGrid, [row("UP", shiftedGrid[6].t)]);
assert.equal(offGridSummary.counts.INVALID_SETUP, 1);
assert.equal(offGridSummary.resolved, 0);
assert.equal(offGridSummary.targetFirstRate, null, "off-grid setups stay outside the resolved rate denominator");
console.log("PATTERN BARRIER OUTCOMES PASS: causal fixed geometry, LONG/SHORT first touches, known opens, ambiguous candles, forming/gapped/malformed paths and reconciled denominators.");
