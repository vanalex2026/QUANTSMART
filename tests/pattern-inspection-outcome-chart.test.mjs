import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(new URL("../mfe_ux_lab/cockpit/package.json", import.meta.url));
const { build } = require("esbuild");
const bundled = await build({ stdin: { contents: 'export * from "./src/lib/patternInspectionWindow.ts"; export * from "./src/components/PatternInspectionChart.tsx";', resolveDir: fileURLToPath(new URL("../mfe_ux_lab/cockpit/", import.meta.url)), loader: "tsx" }, jsx: "automatic", bundle: true, format: "cjs", platform: "node", external: ["react", "react/jsx-runtime"], write: false, logLevel: "silent" });
const mod = { exports: {} };
new Function("require", "module", "exports", bundled.outputFiles[0].text)(require, mod, mod.exports);
const { patternInspectionWindow: inspect, PatternInspectionChart } = mod.exports;
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const bar = (i, extra = {}) => ({ i, r: "N", t: new Date(Date.UTC(2026, 0, 1, 0, i * 5)).toISOString(), o: 100, h: 101, l: 99, c: 100, closed: true, ...extra });
const bars = Array.from({ length: 50 }, (_, i) => bar(i));
const time = bars[10].t;
const setup = inspect(bars, time, "bullish", true);
const full = inspect(bars, time, "bullish", true, "outcome");
const bearish = inspect(bars, time, "bearish", true, "outcome");
assert.equal(setup.rows.length, 13);
assert.equal(full.rows.length, 33, "eight context candles, setup and all 24 observed M5 candles remain available");
assert.equal(full.mode, "outcome"); assert.equal(full.study.state, "TIMEOUT");
assert.equal(full.to, 34); assert.equal(full.rows.at(-1), bars[34]);
assert.deepEqual(full.geometry, setup.geometry, "expanding the display never changes the setup's fixed levels");
const changed = bars.map((b, i) => i === 30 ? { ...b, h: 106 } : b);
const hit = inspect(changed, time, "bullish", true, "outcome");
assert.equal(hit.study.state, "TARGET_FIRST"); assert.equal(hit.study.observedBars, 20);
assert.equal(hit.to, 30); assert.equal(hit.rows.length, 29, "the whole modeled path is shown through its resolving candle");
assert.deepEqual(hit.geometry, full.geometry);
const lateInvalid = inspect(changed.map((b, i) => i === 31 ? { ...b, h: NaN } : b), time, "bullish", true, "outcome");
assert.equal(lateInvalid.to, 30, "invalid data after a resolved event cannot contaminate the displayed path");
const ambiguous = inspect(bars.map((b, i) => i === 12 ? { ...b, h: 106, l: 97 } : b), time, "bullish", true, "outcome");
assert.equal(ambiguous.study.state, "AMBIGUOUS"); assert.equal(ambiguous.to, 12);
const gapTape = bars.filter((_, i) => i !== 12);
const gap = inspect(gapTape, time, "bullish", true, "outcome");
assert.equal(gap.study.state, "DATA_GAP"); assert.equal(gap.rows.at(-1).t, bars[11].t);
assert.equal(inspect(gapTape, time, "bullish", true).rows.at(-1).t, bars[11].t, "compact context cannot silently join candles across a gap either");
for (const extra of [{ h: NaN }, { closed: false }]) {
  const tape = bars.map((b, i) => i === 11 ? { ...b, ...extra } : b);
  const result = inspect(tape, time, "bullish", true, "outcome");
  assert.equal(result.to, 10); assert.equal(result.outcome, null);
  assert.equal(inspect(tape, time, "bullish", true).to, 10, "invalid/forming future rows stay outside both chart modes");
}
const invalidSetup = inspect(bars.map((b, i) => i === 8 ? { ...b, closed: false } : b), time, "bullish", true, "outcome");
assert.equal(invalidSetup.study, null); assert.equal(invalidSetup.mode, "setup"); assert.equal(invalidSetup.geometry.target, null);
assert.equal(invalidSetup.from, 9, "context begins after the unusable setup prefix rather than connecting across it");
const withheld = inspect(bars, time, "bullish", false, "outcome");
assert.equal(withheld.mode, "setup"); assert.equal(withheld.study, null); assert.equal(withheld.geometry.target, null);
const neutral = inspect(bars, time, "neutral", true, "outcome");
assert.equal(neutral.mode, "setup"); assert.equal(neutral.study, null); assert.equal(neutral.geometry.target, null);
const incomplete = inspect(bars.slice(0, 15), time, "bearish", true, "outcome");
assert.equal(incomplete.study.state, "INCOMPLETE"); assert.equal(incomplete.to, 14);
assert.equal(inspect(bars.map((b, i) => i === 10 ? { ...b, closed: false } : b), time, "bullish", true), null);
const shifted = inspect(bars.slice(2), time, "bullish", true, "outcome");
assert.deepEqual(shifted.geometry, full.geometry); assert.equal(shifted.rows.at(-1).t, full.rows.at(-1).t);

const markup = view => renderToStaticMarkup(createElement(PatternInspectionChart, { view, label: "Support / resistance" }));
for (const view of [setup, full, bearish, hit, ambiguous, gap, incomplete, invalidSetup, withheld]) {
  const html = markup(view);
  assert.equal((html.match(/data-inspection-candle-time=/g) || []).length, view.rows.length);
  assert.match(html, /pattern-inspection-price-axis/);
  assert.match(html, /role="region" tabindex="0"/);
  assert.match(html, /Left and Right select candles, Home and End/);
  assert.match(html, /data-inspected-candle="2026-01-01T00:50:00.000Z"/);
  assert.doesNotMatch(html, /NaN|Infinity/);
  if (view.mode === "outcome") assert.match(html, /Inspect last observed outcome candle/);
  if (!view.study) assert.doesNotMatch(html, /data-inspection-position/);
}
assert.match(markup(full), /width="552"/ , "24-bar outcome paths reserve readable candle widths for horizontal scrolling");
assert.match(markup(full), /LONG ENTRY 100\.00/, "directional mini chart labels the side and entry price");
assert.match(markup(full), /TARGET 104\.40/, "directional mini chart labels the target price");
assert.match(markup(full), /INVALIDATION 98\.00/, "directional mini chart labels the invalidation price");
assert.match(markup(bearish), /SHORT ENTRY 100\.00/);
assert.match(markup(bearish), /TARGET 95\.60/);
assert.match(markup(bearish), /INVALIDATION 102\.00/);
assert.match(markup(full), /historical observed path with illustrative research geometry; SHADOW_ONLY \/ NO_DECISION/);
assert.doesNotMatch(markup(neutral), /LONG ENTRY|SHORT ENTRY|TARGET 104\.40|INVALIDATION 98\.00/, "neutral geometry withholds directional captions and prices");
assert.doesNotMatch(markup(withheld), /LONG ENTRY|SHORT ENTRY|TARGET 104\.40|INVALIDATION 98\.00/, "withheld geometry withholds directional captions and prices");
assert.match(markup(hit), /data-inspection-event="TARGET_FIRST"/);
assert.match(markup(ambiguous), /data-inspection-event="AMBIGUOUS"/);
assert.match(markup(ambiguous), /Both touched in one candle; order unknown/);
assert.doesNotMatch(markup(ambiguous), /data-inspection-event="TARGET_FIRST"/);
console.log("PATTERN OUTCOME MINI CHART PASS: complete bounded paths, fixed causal levels, stopped missing/forming data, explicit ambiguity and rendered scrollable candle inspection.");
