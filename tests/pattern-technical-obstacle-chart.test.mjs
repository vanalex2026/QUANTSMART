import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(new URL("../mfe_ux_lab/cockpit/package.json", import.meta.url));
const { build } = require("esbuild");
const bundled = await build({ stdin: { contents: 'export { patternInspectionWindow } from "./src/lib/patternInspectionWindow.ts"; export { PatternInspectionChart } from "./src/components/PatternInspectionChart.tsx";', resolveDir: fileURLToPath(new URL("../mfe_ux_lab/cockpit/", import.meta.url)), loader: "tsx" }, jsx: "automatic", bundle: true, format: "cjs", platform: "node", external: ["react", "react/jsx-runtime"], write: false, logLevel: "silent" });
const mod = { exports: {} };
new Function("require", "module", "exports", bundled.outputFiles[0].text)(require, mod, mod.exports);
const { patternInspectionWindow, PatternInspectionChart } = mod.exports;
const { createElement } = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const bar = (i, fields = {}) => ({ i, t: new Date(Date.UTC(2026, 0, 1, 0, i * 5)).toISOString(), o: 100, h: 101, l: 99, c: 100, closed: true, ...fields });
const bars = Array.from({ length: 130 }, (_, i) => bar(i));
bars[70] = bar(70, { h: 105 });
bars[98] = bar(98, { h: 102 });
bars[99] = bar(99, { h: 104, c: 103 });
const setup = { kind: "PATTERN_BREAK", direction: "UP", confirmationTime: bars[99].t, protectionReference: 95, breakoutLevel: 102, contextBoundary: 101, buildupTimes: [bars[98].t], boundaryTouchTimes: [], signalBarTime: bars[98].t };
const view = patternInspectionWindow(bars, bars[99].t, "bullish", true, "setup", setup);
assert.equal(view.technicalStudy.protection, 95);
assert.equal(view.technicalStudy.obstacle, 105);
const html = renderToStaticMarkup(createElement(PatternInspectionChart, { view, label: "Pattern break", setup }));
assert.match(html, /data-technical-protection="true"/);
assert.match(html, /data-technical-obstacle="true"/);
assert.match(html, /causal 96-bar room context/);
assert.doesNotMatch(html, /NaN|Infinity/);
const withheld = patternInspectionWindow(bars, bars[99].t, "bullish", false, "setup", setup);
assert.equal(withheld.technicalStudy, null, "unverified geometry must withhold technical levels");
console.log("PATTERN TECHNICAL OBSTACLE CHART PASS: causal protection and nearest obstacle lines render separately; withheld geometry emits no levels.");
