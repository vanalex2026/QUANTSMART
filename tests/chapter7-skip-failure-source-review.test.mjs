assert.deepEqual(index.pages.find(row=>row.printed_page===210).concept_ids,[]);
assert.equal(receipt.source_sha256,map.source.sha256);
assert.deepEqual(receipt.newly_curated_printed_pages,[181,182,183,...Array.from({length:24},(_,i)=>187+i)]);
assert.deepEqual(receipt.previously_curated_rechecked_printed_pages,[184,185,186]);
