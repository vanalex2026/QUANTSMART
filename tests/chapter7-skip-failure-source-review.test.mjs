import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=file=>JSON.parse(readFileSync(new URL(file,import.meta.url),'utf8'));
const map=read('../docs/price_action_knowledge_map.json');
const index=read('../docs/price_action_page_index.json');
const receipt=read('../artifacts/chapter7-skip-failure-source-review-181-210.json');
const chapter=map.book_index.find(row=>row.number===7);
const lens=map.source_lenses.find(row=>row.id==='chapter7_skip_failure_conditions');
const fixture=map.held_out_source_fixtures.find(row=>row.id==='chapter-7-skip-failure-review-181-209');
assert.deepEqual(chapter.reviewed_printed_pages,Array.from({length:34},(_,i)=>177+i));
assert.deepEqual(lens.pages,Array.from({length:29},(_,i)=>181+i));
assert.deepEqual(fixture.pages,lens.pages);
assert.equal(lens.implementation,'SOURCE_NOTES');
assert.equal(fixture.status,'SOURCE_REVIEW_ONLY');
assert.equal(fixture.data_status,'UNAVAILABLE');
assert.equal(fixture.outcome_status,'WITHHELD');
